"""Structural numeric contracts shared by separately versioned research pipelines."""

from datetime import datetime
from decimal import Decimal
from typing import Protocol


class NumericVector(Protocol):
    @property
    def values(self) -> tuple[float, ...]: ...


class TimedVector(NumericVector, Protocol):
    @property
    def time(self) -> datetime: ...


class Outcome(Protocol):
    @property
    def features(self) -> TimedVector: ...
    @property
    def target(self) -> int: ...
    @property
    def net_pnl(self) -> Decimal: ...
    @property
    def label_end(self) -> datetime: ...


class ValidationIdentity(Protocol):
    @property
    def training_sha256(self) -> str: ...
    @property
    def samples_manifest_sha256(self) -> str: ...
    @property
    def synthetic(self) -> bool: ...
    @property
    def embargo_minutes(self) -> int: ...
    @property
    def threshold(self) -> float: ...
    @property
    def fit_label_end(self) -> datetime: ...
    @property
    def validation_label_end(self) -> datetime: ...
    @property
    def validated_through(self) -> datetime: ...
